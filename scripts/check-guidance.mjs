import { existsSync, readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { isDeepStrictEqual } from 'node:util';
import { impactTable, selectTests } from './test-changed.mjs';
import { isMain, matches, readJson, repositoryFiles, ROOT, testFiles } from './repo-utils.mjs';

export function withoutFences(markdown) {
	let fence;
	return markdown.split('\n').filter((line) => {
		const match = /^\s*(`{3,}|~{3,})/.exec(line);
		if (!fence && match) { fence = match[1]; return false; }
		if (fence && match && match[1][0] === fence[0] && match[1].length >= fence.length) { fence = undefined; return false; }
		return !fence;
	}).join('\n');
}

export function markdownLinks(markdown) {
	const text = withoutFences(markdown);
	// Repository links use inline/reference Markdown or HTML src/href. Remote URLs and heading anchors are not crawled.
	return [
		...text.matchAll(/\]\(\s*(?:<([^>\n]+)>|([^\s)]+))/g),
		...text.matchAll(/^\s*\[[^\]\n]+\]:\s*(?:<([^>\n]+)>|(\S+))/gm),
		...text.matchAll(/\b(?:src|href)=["']([^"']+)["']/g),
	].map((match) => match[1] ?? match[2]);
}

export function resolveLink(root, source, target) {
	if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(target)) return null;
	const pathname = decodeURIComponent(target.split(/[?#]/, 1)[0]);
	if (!pathname) return null;
	if (source.startsWith('docs/') && /^\/api(?:\/|$)/.test(pathname)) return null; // Generated by docs:api.
	const file = pathname.startsWith('/') && source.startsWith('docs/')
		? path.join(root, 'docs', pathname.slice(1)) : path.resolve(root, path.dirname(source), pathname);
	const relative = path.relative(root, file);
	if (relative.startsWith('..') || path.isAbsolute(relative)) throw new Error(`Link escapes repository: ${source} -> ${target}`);
	const candidates = path.extname(file) ? [file] : [`${file}.md`, path.join(file, 'index.md'), file];
	const found = candidates.find((candidate) => existsSync(candidate));
	if (!found) throw new Error(`Broken link: ${source} -> ${target}`);
	return path.relative(root, found).replaceAll('\\', '/');
}

export function checkCommands(text, scripts) {
	const builtins = new Set(['install', 'add', 'remove', 'update', 'exec', 'dlx', 'pack', 'publish']);
	for (const [, command] of text.matchAll(/\bpnpm[ \t]+(?:run[ \t]+)?([a-z][\w:-]*)/g)) {
		if (!builtins.has(command) && !Object.hasOwn(scripts, command)) throw new Error(`Unknown pnpm command: ${command}`);
	}
}

export function markdownCode(text) {
	return [
		...text.matchAll(/`([^`\n]+)`/g),
		...text.matchAll(/^(?:`{3,}|~{3,})[^\n]*\n([\s\S]*?)^(?:`{3,}|~{3,})/gm),
	].map((match) => match[1]).join('\n');
}

export function changelogStructure(text) {
	const categories = new Map([
		['Features:', 'features'], ['新功能：', 'features'], ['Fixes:', 'fixes'], ['修复：', 'fixes'],
		['Other:', 'other'], ['其他：', 'other'], ['Breaking changes:', 'breaking'], ['破坏性变更：', 'breaking'],
	]);
	const result = [];
	let section;
	let category;
	for (const line of text.split(/\r?\n/)) {
		const version = /^### (v\d+\.\d+\.\d+(?:-[\w.]+)?)/.exec(line)?.[1];
		if (version || /^## (Unreleased|未发布)$/.test(line)) {
			const url = version ? /\]\((https:\/\/github\.com\/[^)]+)\)/.exec(line)?.[1] : undefined;
			if (version && (!url || !url.endsWith(`/${version}`))) throw new Error(`Missing/mismatched release link: ${version}`);
			section = { version: version ?? 'unreleased', url, categories: [] };
			if (result.some((entry) => entry.version === section.version)) throw new Error(`Duplicate changelog version: ${section.version}`);
			result.push(section);
			category = undefined;
		} else if (/^## /.test(line)) { section = undefined; category = undefined; }
		else if (section && categories.has(line)) {
			category = { name: categories.get(line), count: 0 };
			if (section.categories.some((entry) => entry.name === category.name)) throw new Error(`Duplicate changelog category: ${section.version}/${category.name}`);
			section.categories.push(category);
		} else if (category && /^- /.test(line)) category.count += 1;
	}
	if (result.length < 2) throw new Error('Changelog must include Unreleased and at least one version.');
	return result;
}

export function checkGuidance(root) {
	const files = repositoryFiles(root).filter((file) => existsSync(path.join(root, file)));
	const scripts = readJson(path.join(root, 'package.json')).scripts;
	const references = readJson(path.join(root, 'references.json'));
	const map = readJson(path.join(root, 'agent/impact-map.json'));
	const available = testFiles(root);
	selectTests(map, [], available); // All configured groups must be non-empty and cover the full test inventory.
	for (const rule of map.rules) {
		for (const group of rule.tests) if (!map.tests[group]) throw new Error(`Unknown test group: ${group}`);
		for (const doc of rule.docs) if (!existsSync(path.join(root, doc))) throw new Error(`Missing impact-map document: ${doc}`);
		for (const pattern of rule.paths) if (!files.some((file) => matches(file, pattern))) throw new Error(`Stale impact-map path: ${pattern}`);
	}
	const agents = ['AGENTS.md', ...readdirSync(path.join(root, 'packages'), { withFileTypes: true })
		.filter((entry) => entry.isDirectory()).map((entry) => `packages/${entry.name}/AGENTS.md`)];
	for (const file of agents) {
		if (!files.includes(file)) throw new Error(`Missing or ignored agent guidance: ${file}`);
		const text = readFileSync(path.join(root, file), 'utf8');
		if (file !== 'AGENTS.md' && !markdownLinks(text).includes('../../AGENTS.md')) throw new Error(`Missing root guidance link: ${file}`);
		for (const [, token] of withoutFences(text).matchAll(/`([^`\n]+)`/g)) {
			if (!/^(?:packages\/|scripts\/|docs\/|agent\/|references\.json$|\.node-version$)/.test(token)) continue;
			if (!files.some((entry) => matches(entry, token)) && !existsSync(path.join(root, token))) throw new Error(`Stale agent path: ${file}: ${token}`);
		}
	}
	const rootGuidance = readFileSync(path.join(root, 'AGENTS.md'), 'utf8');
	const generated = /<!-- impact-map:start -->\r?\n([\s\S]*?)\r?\n<!-- impact-map:end -->/.exec(rootGuidance)?.[1];
	if (generated?.replaceAll('\r\n', '\n') !== impactTable(map)) throw new Error('Impact table drift. Run pnpm test:changed --matrix and update the marked AGENTS.md section.');
	for (const entry of references.submodules) {
		if (!entry.authority || !entry.probe) throw new Error(`Incomplete reference metadata: ${entry.path}`);
	}
	for (const entry of references.local) {
		if (!entry.id || !entry.authority || !entry.acquire || !entry.paths.length || !Object.hasOwn(entry, 'source') || !Object.hasOwn(entry, 'revision')) {
			throw new Error('Local references must declare provenance (null when unknown), authority and acquisition limits.');
		}
	}
	const paths = readJson(path.join(root, 'tsconfig.json')).compilerOptions.paths;
	for (const [name, targets] of Object.entries(paths)) {
		for (const target of targets) if (!existsSync(path.resolve(root, target))) throw new Error(`Stale public source mapping: ${name} -> ${target}`);
	}
	const documents = files.filter((file) => file.endsWith('.md') && !file.includes('/fixtures/'));
	const links = new Map();
	for (const file of documents) {
		const text = readFileSync(path.join(root, file), 'utf8');
		try {
			checkCommands(markdownCode(text), scripts);
			links.set(file, markdownLinks(text).map((target) => resolveLink(root, file, target)).filter(Boolean));
		} catch (error) { throw new Error(`${file}: ${error.message}`); }
	}
	for (const command of Object.values(scripts)) checkCommands(command, scripts);
	for (const [left, right] of [['README.md', 'README_EN.md'], ['docs/README.md', 'docs/en/README.md']]) {
		const normalized = (file) => [...new Set(links.get(file).filter((target) => target.startsWith('docs/') && target.endsWith('.md'))
			.map((target) => target.replace(/^docs\/en\//, 'docs/')).filter((target) => target !== 'docs/README.md'))].sort();
		if (!isDeepStrictEqual(normalized(left), normalized(right))) throw new Error(`Bilingual documentation entry drift: ${left} / ${right}`);
	}
	const structure = (file) => changelogStructure(readFileSync(path.join(root, file), 'utf8'));
	if (!isDeepStrictEqual(structure('CHANGELOG.md'), structure('CHANGELOG_CN.md'))) throw new Error('Bilingual changelog version/link/category/item-count drift. Translation meaning still requires review.');
	return { documents: documents.length, agentFiles: agents.length, tests: available.length };
}

if (isMain(import.meta.url)) {
	try { console.log('Repository guidance checks passed:', checkGuidance(ROOT)); }
	catch (error) { console.error(error.message); process.exitCode = 1; }
}
